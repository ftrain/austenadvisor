// docs/before-after.md: each everyday sample in samples/, and what the engine alone makes of it, change by change,
// each change with its reason and a sentence of the author's. With --ai, Claude's rewrite (with the engine as its
// tools) beside it.
//
//   node scripts/before-after.ts [--ai] [--author austen]

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from '../src/db.ts';
import { analyze } from '../src/engine/analyze.ts';
import { austenize } from '../src/engine/austenize.ts';
import { blocksOfText, textOfBlocks } from '../src/engine/doc.ts';
import { AuthorModel } from '../src/engine/model.ts';
import { aiAvailable, rewriteWithAI } from '../src/server/rewrite.ts';

const args = process.argv.slice(2);
const withAI = args.includes('--ai') && aiAvailable();
const ai = args.indexOf('--author');
const m = AuthorModel.load(ai >= 0 ? args[ai + 1]! : 'austen');
const short = m.author.short;
const quote = (s: string) => s.split('\n').map((l) => `> ${l}`).join('\n');

const out: string[] = [
  `# Everyday prose, ${short}ed`,
  '',
  `Six pieces of ordinary modern prose (in [samples/](../samples/)), and what ${m.author.advisor}'s engine makes of them **with no language model**: every word ${short} never wrote replaced by her nearest word in meaning (WordNet senses, her own inflections, her trigram model and word vectors), contractions written out where she wrote them out, words swapped where her usage strongly prefers another, and runs of short sentences joined as she joined clauses. Every change is listed with the numbers behind it and a sentence of hers, cited.`,
  '',
  `This is a first draft by statistics, and it shows both what statistics catch and what they cannot: a word chosen for its dictionary sense without its idiom (“said countenance” for “said okay”), a modern thing with no Regency word (“phone”, “hoodie”), left alone and listed. That gap is what “Rewrite with AI” is for: Claude rewrites the passage with this same engine as its tools, checks its draft against ${short}’s works, and cites the sentences it learned from.`,
  '',
  `Generated by \`node scripts/before-after.ts\`${withAI ? ' --ai' : ''} on ${new Date().toISOString().slice(0, 10)} from ${m.totalWords.toLocaleString()} words of ${m.author.name}.`,
  '',
];

for (const f of readdirSync(join(ROOT, 'samples')).filter((x) => x.endsWith('.txt')).sort()) {
  const text = readFileSync(join(ROOT, 'samples', f), 'utf8');
  const blocks = blocksOfText(text);
  const titleBlock = blocks.find((b) => b.kind === 'title');
  const body = blocks.filter((b) => b.kind !== 'title');
  const before = analyze(m, body);
  const r = austenize(m, body);
  out.push(`## ${titleBlock?.text ?? f}`, '');
  out.push(`**Before** — ${before.report.score}/100 like ${short}; ${before.words.filter((w) => w.kind !== 'name').length} words she never wrote: ${before.words.filter((w) => w.kind !== 'name').map((w) => `*${w.word}*`).join(', ')}.`, '');
  out.push(quote(textOfBlocks(body)), '');
  out.push(`**After, by statistics alone** — ${r.scoreAfter}/100.`, '');
  out.push(quote(textOfBlocks(r.after)), '');
  out.push('<details><summary>Every change, and why</summary>', '');
  for (const c of r.changes) {
    out.push(`- “${c.before}” → “${c.after}”. ${c.why}${c.example ? `\n  > ${c.example.text}\n  > — *${c.example.cite}*` : ''}`);
  }
  if (r.kept.length) out.push(`- Kept, with no word of ${short}’s near enough: ${r.kept.map((k) => `*${k.word}*`).join(', ')}.`);
  out.push('', '</details>', '');
  if (withAI) {
    const res = await rewriteWithAI(m, textOfBlocks(body), {}, (s) => console.error(`${f}: ${s}`));
    out.push(`**After, Rewrite with AI** (${res.model}, ${res.toolCalls.length} calls to the engine) — ${res.scoreAfter}/100.`, '', quote(res.text), '', res.explanation, '');
    for (const n of res.notes) out.push(`- ${n.technique}: “${n.before}” → “${n.after}”\n  > ${n.austen}\n  > — *${n.cite}* ${n.verified ? '(verified in the corpus)' : '(⚠ not found in the corpus)'}`);
    out.push('');
  }
}
if (!withAI) out.push('---', '', `To add Claude’s rewrite of each piece beside these, set \`ANTHROPIC_API_KEY\` and run \`node scripts/before-after.ts --ai\`.`, '');
writeFileSync(join(ROOT, 'docs', 'before-after.md'), out.join('\n'));
console.log(`docs/before-after.md: ${readdirSync(join(ROOT, 'samples')).length} samples`);
